// ภาพสี่รูปเรียงแถวเดียวโดยไม่มีเส้นตาราง
function imgRow(items, w, h) {
  const none = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' };
  const bd = { top: none, bottom: none, left: none, right: none,
               insideHorizontal: none, insideVertical: none };
  const cw = Math.round(CONTENT_DXA / items.length);
  return new Table({
    columnWidths: items.map(() => cw),
    width: { size: CONTENT_DXA, type: WidthType.DXA },
    borders: bd,
    rows: [new TableRow({
      cantSplit: true,          // ห้ามตัดแถวข้ามหน้า ไม่งั้นภาพกับคำบรรยายจะแยกคนละหน้า
      children: items.map((it) => new TableCell({
        width: { size: cw, type: WidthType.DXA }, borders: bd,
        children: [img(it.file, w, h), caption(it.cap)],
      })),
    })],
  });
}

