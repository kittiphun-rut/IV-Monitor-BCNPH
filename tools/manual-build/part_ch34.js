// ---- ผังขั้นตอน: กล่องเรียงลงมาพร้อมลูกศร ----
function flowBox(text, fill = 'EAF1FB') {
  const bd = { style: BorderStyle.SINGLE, size: 8, color: '2E5C8A' };
  const w = Math.round(CONTENT_DXA * 0.72);
  return new Table({
    columnWidths: [w], width: { size: w, type: WidthType.DXA },
    alignment: AlignmentType.CENTER,
    borders: { top: bd, bottom: bd, left: bd, right: bd, insideHorizontal: bd, insideVertical: bd },
    rows: [new TableRow({ children: [new TableCell({
      width: { size: w, type: WidthType.DXA },
      shading: { type: ShadingType.CLEAR, fill, color: 'auto' },
      margins: { top: 80, bottom: 80, left: 120, right: 120 },
      children: [new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 0 },
                                 children: [run(text, { size: 30 })] })],
    })] })],
  });
}
